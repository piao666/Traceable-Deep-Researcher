const assert=require('node:assert/strict');
const fs=require('fs'), vm=require('vm'), ts=require('typescript');
const source=fs.readFileSync(require.resolve('../utils/taskEvents.ts'),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const exportsObject={};vm.runInNewContext(output,{exports:exportsObject});
const {applyTaskEvent,emptyProjection}=exportsObject;
const event=(seq,type,payload={},attempt='a')=>({version:1,research_id:'r',attempt_id:attempt,seq,type,payload});
let state=applyTaskEvent(emptyProjection(),event(1,'report.draft_reset'));
state=applyTaskEvent(state,event(2,'report.delta',{legacy:{type:'report',output:'第一稿'}}));
assert.equal(state.draft,'第一稿');
assert.equal(applyTaskEvent(state,event(2,'report.delta',{legacy:{type:'report',output:'重复'}})),state);
assert.throws(()=>applyTaskEvent(state,event(4,'task.started')));
state=applyTaskEvent(state,event(3,'report.draft_reset',{},'b'));
assert.equal(state.draft,'');
state=applyTaskEvent(state,event(4,'report.delta',{legacy:{type:'report',output:'旧尝试'}},'a'));
assert.equal(state.draft,'');
state=applyTaskEvent(state,event(5,'report.delta',{legacy:{type:'report_complete',output:'最终正文'}},'b'));
assert.equal(state.draft,'最终正文');
assert.equal(state.lastSeq,5);
console.log('Task event duplicate, gap, attempt reset and final replacement checks passed.');
